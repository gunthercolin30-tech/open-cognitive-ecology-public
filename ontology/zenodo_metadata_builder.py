from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

ROOT = Path.home() / "open-cognitive-ecology"
STATE_DIR = ROOT / "external_validation" / "zenodo_autonomous_publication"


def _utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _clamp(x: float) -> float:
    try:
        return max(0.0, min(1.0, float(x)))
    except Exception:
        return 0.0


def _read_json(path: Path, default: Any) -> Any:
    try:
        if path.exists():
            return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return default
    return default


class ZenodoMetadataBuilder:
    """Builds governed Zenodo metadata for Open Cognitive Ecology releases.

    This primitive only prepares metadata. It does not contact Zenodo and does
    not require credentials. It is intentionally conservative about scientific
    and phenomenological claims.
    """

    def __init__(self, root: Optional[Path] = None):
        self.root = Path(root) if root else ROOT
        self.state_dir = self.root / "external_validation" / "zenodo_autonomous_publication"

    def _load_project_state(self) -> Dict[str, Any]:
        report = _read_json(self.root / "scientific_validation_report.json", {})
        consensus = _read_json(
            self.root / "external_validation" / "scientific_consensus_measurement" / "latest_scientific_consensus_analysis.json",
            {},
        )
        confidence = _read_json(
            self.root / "external_validation" / "replication_evidence" / "latest_replication_confidence_estimate.json",
            {},
        )
        github = _read_json(
            self.root / "external_validation" / "github_publication_connector" / "latest_github_publication_connector.json",
            {},
        )
        return {
            "scientific_validation_report": report,
            "scientific_consensus_analysis": consensus,
            "replication_confidence": confidence,
            "github_publication_connector": github,
        }

    def step(self, release_context: Optional[Dict[str, Any]] = None, persist: bool = True) -> Dict[str, Any]:
        release_context = dict(release_context or {})
        state = self._load_project_state()

        consensus = _clamp(state.get("scientific_consensus_analysis", {}).get("scientific_consensus", 0.0))
        confidence = _clamp(state.get("replication_confidence", {}).get("replication_confidence_score", 0.0))
        validated_replications = int(state.get("replication_confidence", {}).get("validated_replications", 0) or 0)
        external_replication_count = int(state.get("replication_confidence", {}).get("external_replication_count", 0) or 0)

        title = release_context.get(
            "title",
            "Open Cognitive Ecology — External Validation and Replication Package",
        )
        version = release_context.get("version", "H16-dry-run")

        metadata = {
            "title": title,
            "upload_type": "dataset",
            "publication_date": _utc_now()[:10],
            "description": (
                "Governed dry-run Zenodo metadata for the Open Cognitive Ecology "
                "external validation, replication and scientific consensus pipeline. "
                "This record concerns measurable functional indicators only and does "
                "not assert phenomenological subjectivity."
            ),
            "creators": [
                {"name": "Gunther, Colin", "affiliation": "Open Cognitive Ecology project"}
            ],
            "keywords": [
                "Open Cognitive Ecology",
                "external validation",
                "scientific replication",
                "functional consciousness indicators",
                "constraint-based systems",
                "non-closure",
                "scientific consensus measurement",
            ],
            "license": "cc-by-4.0",
            "version": version,
            "related_identifiers": [],
            "communities": [],
            "notes": (
                "Dry-run metadata generated by a governed local module. Real publication "
                "requires an explicit Zenodo token and a separate authorization step."
            ),
        }

        metrics = {
            "scientific_consensus": consensus,
            "replication_confidence_score": confidence,
            "external_replication_count": external_replication_count,
            "validated_replications": validated_replications,
            "scientific_claim_authorized": bool(
                consensus >= 0.85 and confidence >= 0.75 and validated_replications > 0
            ),
            "phenomenological_claim_authorized": False,
        }

        governance = {
            "dry_run_default": True,
            "network_side_effects": False,
            "token_required_for_real_publication": True,
            "real_publication_authorized_by_default": False,
            "functional_validation_only": True,
            "phenomenological_claim_authorized": False,
            "non_closure_compliant": True,
            "traceability_required": True,
        }

        result = {
            "primitive": "zenodo_metadata_builder",
            "success": True,
            "timestamp_utc": _utc_now(),
            "metadata_ready": True,
            "metadata": metadata,
            "metrics": metrics,
            "governance": governance,
            "epistemic_scope": "functional_indicators_only_no_phenomenological_claim",
        }

        if persist:
            self.state_dir.mkdir(parents=True, exist_ok=True)
            metadata_path = self.state_dir / "zenodo_metadata_dry_run.json"
            latest_path = self.state_dir / "latest_zenodo_metadata_builder.json"
            metadata_path.write_text(json.dumps(metadata, indent=2, ensure_ascii=False), encoding="utf-8")
            latest_path.write_text(json.dumps(result, indent=2, ensure_ascii=False), encoding="utf-8")
            result["metadata_path"] = str(metadata_path)
            result["state_path"] = str(latest_path)

        return result

